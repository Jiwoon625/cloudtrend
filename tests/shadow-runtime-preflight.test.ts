import { expect, it } from "vitest";
import { readFile, writeFile, mkdir, mkdtemp, rm } from "node:fs/promises";
import path from "node:path";
import { tmpdir } from "node:os";
import { shadowEngineManifest } from "../scripts/october-shadow-code-manifest";
import { integratedAllocationRuntimeManifest } from "../scripts/integrated-allocation-code-manifest";
import { verifyShadowRuntimeManifests } from "../scripts/verify-shadow-runtime-manifests";
import { integratedCompatibilityScenario } from "./fixtures/integrated-runtime-compatibility-scenario";
import golden from "./fixtures/integrated-runtime-prechange-3dd1209.json";

it("matches independently executed prechange commit economic publications byte-for-byte", async () => {
  // Golden was generated by this same synthetic fixture in a git-archive checkout
  // of 3dd1209e30d6cce19fdccf1ea1a7693af14f3169, not from candidate code.
  expect(await integratedCompatibilityScenario()).toEqual(golden);
  expect(golden.O1.outputs[0]!.pendingBuys).toBeGreaterThan(0);
  expect(golden.O1.outputs[1]!.positions).toBeGreaterThan(0);
  expect(golden.O1.outputs[2]!.positions).toBe(0);
});

it("checks actual executable sources rather than trusting stale generated hashes", async () => {
  const root = await mkdtemp(path.join(tmpdir(), "shadow-runtime-preflight-"));
  try {
    const [october, copiedIntegrated] = await Promise.all([
      shadowEngineManifest(),
      integratedAllocationRuntimeManifest(),
    ]);
    const files = new Set([
      ...Object.keys(october.manifest.files),
      ...Object.keys(copiedIntegrated.manifest.files),
    ]);
    for (const file of files) {
      await mkdir(path.dirname(path.join(root, file)), { recursive: true });
      await writeFile(path.join(root, file), await readFile(file));
    }
    await writeFile(
      path.join(root, "src/lib/ledger/octoberShadowEngineManifest.generated.json"),
      JSON.stringify(october),
    );
    // Integrated includes the October generated manifest. Recompute only after
    // writing the fresh October artifact, then prove the fixture is not stale.
    const integrated = await integratedAllocationRuntimeManifest(root);
    await writeFile(
      path.join(root, "src/lib/integratedAllocationRuntime.generated.json"),
      JSON.stringify(integrated),
    );
    expect(await shadowEngineManifest(root)).toEqual(october);
    expect(await integratedAllocationRuntimeManifest(root)).toEqual(integrated);
    const target = path.join(root, "src/lib/integratedAllocationShadow.ts");
    await writeFile(
      target,
      (await readFile(target, "utf8")) + "\nexport const STALE_RUNTIME_TEST = 1;\n",
    );
    expect((await integratedAllocationRuntimeManifest(root)).codeHash).not.toBe(
      integrated.codeHash,
    );
    expect(await shadowEngineManifest(root)).toEqual(october);
    await expect(verifyShadowRuntimeManifests(root)).rejects.toThrow(
      "Stale Shadow executable manifest",
    );
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}, 30000);

it("guards each production CLI and build before source/publication work", async () => {
  for (const name of [
    "run-screening.ts",
    "run-us-screening.ts",
    "run-us-gap-replay.ts",
    "run-kospi-shadow.ts",
  ]) {
    const text = await readFile(`scripts/${name}`, "utf8");
    expect(text).toContain('from "./verify-shadow-runtime-manifests"');
    expect(text).toMatch(
      /await verifyShadowRuntimeManifests\(\)|verifyShadowRuntimeManifests\(\)\s*\.then/,
    );
  }
  const pkg = JSON.parse(await readFile("package.json", "utf8"));
  expect(pkg.scripts.prebuild).toContain("verify-shadow-runtime-manifests.ts");
  expect(pkg.scripts.predev).toContain("verify-shadow-runtime-manifests.ts");
});
