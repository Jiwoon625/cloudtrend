/** 종목의 테마 섹터 코드를 반환한다. */
export function resolveSectorCode(
  symbol: string,
  name: string,
  isEtf: boolean,
): { code: string; name: string } {
  const safeName = name ?? "";
  let code: string | undefined;

  if (isEtf) {
    code = ETF_KEYWORD_RULES.find(([re]) => re.test(safeName))?.[1];
  } else {
    code = SYMBOL_SECTOR[symbol];
    if (!code) code = STOCK_NAME_RULES.find(([re]) => re.test(safeName))?.[1];
    // 우선주(예: 005935)는 본주 코드 뒤 5/7로 끝나는 경우가 많다.
    if (!code && /^\d{6}$/.test(symbol) && !symbol.endsWith("0")) {
      code = SYMBOL_SECTOR[`${symbol.slice(0, 5)}0`];
    }
  }

  const resolved = code ?? "ETC";
  return { code: resolved, name: SECTOR_NAME_BY_CODE[resolved] ?? "기타" };
}
